"""Small contracts for SDK extensions. No Tk, capture, or native dependencies."""

from __future__ import annotations
from typing import Protocol, Sequence
from tibia_client.models import Action, ActionResult, FeatureContext, ObservationBatch, Sensor, Step


class Token(Protocol):
    @property
    def cancelled(self) -> bool: ...
    def checkpoint(self) -> None: ...
    def wait(self, seconds: float) -> None: ...


class Clock(Protocol):
    def monotonic(self) -> float: ...


class ClientAdapter(Protocol):
    def ready(self) -> bool: ...
    def observe(self, sensors: Sequence[Sensor], token: Token) -> ObservationBatch: ...
    def execute(self, action: Action, token: Token) -> None: ...
    def close(self) -> None: ...


class Feature(Protocol):
    name: str
    interval: float

    def sensors(self) -> tuple[Sensor, ...]: ...
    def tick(self, context: FeatureContext) -> Step: ...
    def on_result(self, result: ActionResult) -> None: ...
